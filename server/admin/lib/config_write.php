<?php
/**
 * Writing storage/config.php from the settings page.
 *
 * Pure helpers (validate, merge, render, describe) plus one atomic writer, so
 * the page itself stays a thin form handler and the rules are testable from
 * the CLI. A secret is never returned by anything here except the merge.
 */
declare(strict_types=1);

// Included by the entry points only — never served directly.
if (!defined('ADMIN_DIR')) {
    http_response_code(404);
    exit;
}

/** Google's web client ids: `<digits>-<alnum>.apps.googleusercontent.com`. */
function google_client_id_valid(string $id): bool
{
    return strlen($id) <= 200 && (bool) preg_match('/^[0-9]{6,30}-[a-z0-9]{10,64}\.apps\.googleusercontent\.com$/', $id);
}

/** Client secrets are opaque; only the shape is checked (`GOCSPX-…` today). */
function google_client_secret_valid(string $secret): bool
{
    return (bool) preg_match('/^[A-Za-z0-9_-]{16,128}$/', $secret);
}

/**
 * `$current` with the Google keys updated. An empty field keeps the stored
 * value, so the id can be corrected without retyping the secret. Returns the
 * new config, or an error code (`empty`, `bad_id`, `bad_secret`) — never the input.
 */
function config_with_google(array $current, string $clientId, string $clientSecret): array|string
{
    $clientId = trim($clientId);
    $clientSecret = trim($clientSecret);
    if ($clientId === '' && $clientSecret === '') {
        return 'empty';
    }
    if ($clientId !== '' && !google_client_id_valid($clientId)) {
        return 'bad_id';
    }
    if ($clientSecret !== '' && !google_client_secret_valid($clientSecret)) {
        return 'bad_secret';
    }
    $next = $current;
    if ($clientId !== '') {
        $next['google_client_id'] = $clientId;
    }
    if ($clientSecret !== '') {
        $next['google_client_secret'] = $clientSecret;
    }
    $next['google_updated_at'] = time();
    return $next;
}

/** The PHP source of config.php for `$cfg`. var_export quotes every value. */
function config_render(array $cfg): string
{
    return "<?php\n// Generated by setup and the admin settings page. Never commit this file.\nreturn "
        . var_export($cfg, true) . ";\n";
}

/**
 * Replaces `$target` atomically: a 0600 temp file in the same directory, fully
 * written and flushed, then rename(). A reader sees the old file or the new
 * one, never half of either. OPcache is told the file changed.
 */
function config_write_atomic(string $target, array $cfg): bool
{
    $dir = dirname($target);
    $tmp = $dir . '/.config.' . bin2hex(random_bytes(8)) . '.tmp';
    $fh = @fopen($tmp, 'x');
    if ($fh === false) {
        return false;
    }
    @chmod($tmp, 0600);
    $src = config_render($cfg);
    $ok = fwrite($fh, $src) === strlen($src) && fflush($fh);
    fclose($fh);
    if (!$ok || !@rename($tmp, $target)) {
        @unlink($tmp);
        return false;
    }
    @chmod($target, 0600);
    if (function_exists('opcache_invalidate')) {
        @opcache_invalidate($target, true);
    }
    return true;
}

/**
 * What the page may show: whether each key is set, and the client id's last 12
 * characters. The fixed `.apps.googleusercontent.com` suffix is set aside first,
 * or every id would end in the same 12 characters.
 */
function config_google_status(array $cfg): array
{
    $id = is_string($cfg['google_client_id'] ?? null) ? $cfg['google_client_id'] : '';
    $distinct = preg_replace('/\.apps\.googleusercontent\.com$/', '', $id) ?? '';
    $secret = is_string($cfg['google_client_secret'] ?? null) ? $cfg['google_client_secret'] : '';
    return [
        'client_id_set' => $id !== '',
        'client_id_tail' => $id === '' ? '' : substr($distinct, -12),
        'secret_set' => $secret !== '',
        'updated_at' => is_int($cfg['google_updated_at'] ?? null) ? $cfg['google_updated_at'] : null,
    ];
}
